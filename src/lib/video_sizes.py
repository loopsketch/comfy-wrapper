"""手元から解像度を指定するときの換算表。

サーバ側 (`server/video_common.py`) が持つのは「megapixels からキャンバスを起こす」
計算で、こちらは「480p / 720p / 1080p という言い方を、モデルごとの
(生成キャンバスの megapixels, 出力の短辺) に落とす」表。呼ぶ側が解像度を
数字ではなく名前で言えるようにするためだけにある。

**生成解像度の上限はモデルごとに違う。** H3 は短辺768px・最大 768x1344
(= 0.98MP、1MP は 1024x1024 換算) が上限で、1080p は生成をネイティブ上限で行い
出力段で 1920x1080 へ引き上げる。Wan2.2 と LTX-2.3 は 720p をネイティブで生成でき、
LTX は 1080p もそのまま出せる(そのぶん時間もかかる)。
"""

from __future__ import annotations

RESOLUTIONS = {
    "480p": (0.4, 480),
    "720p": (0.9, 720),
    "1080p": (0.98, 1080),
}

MODEL_RESOLUTIONS = {
    "minimax-h3": RESOLUTIONS,
    # 14B は 832x480 / 1280x720 が素の解像度。1080p は 720p 生成からの拡大
    "wan2.2": {"480p": (0.38, 480), "720p": (0.88, 720), "1080p": (0.88, 1080)},
    # TI2V-5B は 1280x704 が素。480p 生成は学習範囲を外れるので 720p 相当で回す
    "wan2.2-5b": {"480p": (0.38, 480), "720p": (0.86, 720), "1080p": (0.86, 1080)},
    # S2V。音声で駆動する。1チャンク 77フレーム(16fps で 4.81秒)が上限
    "wan2.2-s2v": {"480p": (0.38, 480), "720p": (0.88, 720), "1080p": (0.88, 1080)},
    # LTX は前半を半解像度で回してから x2 に上げるので、指定はそのまま最終解像度
    "ltx-2.3": {"480p": (0.4, 480), "720p": (0.86, 720), "1080p": (1.94, 1080)},
    # Q4_K_M 量子化版。解像度の扱いは fp8 と同じで、L4 の VRAM に載るのはこちら
    "ltx-2.3-gguf": {"480p": (0.4, 480), "720p": (0.86, 720), "1080p": (1.94, 1080)},
    # 参照シートつき (IC-LoRA Ingredients)。単パスなので同じ解像度でも軽い
    "ltx-2.3-ic": {"480p": (0.4, 480), "720p": (0.86, 720), "1080p": (1.94, 1080)},
    # 2.5。解像度の扱いは 2.3 と同じ(前半が半解像度、後半で x2)
    "ltx-2.5": {"480p": (0.4, 480), "720p": (0.86, 720), "1080p": (1.94, 1080)},
}

# 音声つきで出るモデル。あとから音を載せ替えるかの判断に使う
AUDIO_MODELS = {"minimax-h3", "ltx-2.3", "ltx-2.3-gguf", "ltx-2.3-ic", "ltx-2.5"}

ASPECT_RATIOS = {
    "16x9": (16, 9),
    "9x16": (9, 16),
    "1x1": (1, 1),
    "4x3": (4, 3),
    "3x4": (3, 4),
    "21x9": (21, 9),
}


def output_size(aspect: str, short_edge: int) -> tuple[int, int]:
    """アスペクトと短辺から、h264 が扱える偶数寸法の出力サイズを求める。"""
    w_ratio, h_ratio = ASPECT_RATIOS[aspect]
    if w_ratio >= h_ratio:
        height = short_edge
        width = round(short_edge * w_ratio / h_ratio / 2) * 2
    else:
        width = short_edge
        height = round(short_edge * h_ratio / w_ratio / 2) * 2
    return width, height
